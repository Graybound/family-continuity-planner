import { describe, expect, it } from 'vitest';
import { readFileSync } from 'node:fs';
import { parseBackup, safeJsonParse, serializeBackup, backupFileName } from '../../src/core/backup';
import { blankPlan, SCHEMA_VERSION } from '../../src/core/plan';
import { samplePlan } from '../../src/core/sample';
import { LIMITS } from '../../src/core/normalize';

const legacyText = readFileSync(new URL('../fixtures/legacy-v1-export.json', import.meta.url), 'utf8');
const NOW = new Date('2026-11-07T12:00:00Z');

describe('legacy v1 backups (generated by the recovered app)', () => {
  const r = parseBackup(legacyText, { now: NOW });
  it('imports successfully', () => {
    expect(r.ok).toBe(true);
  });
  it('keeps every record, field, and line break', () => {
    if (!r.ok) throw new Error('import failed');
    const v1 = JSON.parse(legacyText);
    for (const s of ['people', 'contacts', 'health', 'home', 'accounts', 'documents', 'plans', 'notes'] as const) {
      expect(r.plan.records[s]).toHaveLength(v1[s].length);
      v1[s].forEach((old: Record<string, string>, i: number) => {
        for (const [k, v] of Object.entries(old)) expect(r.plan.records[s][i]![k]).toBe(v);
      });
    }
    expect(r.plan.records.people[1]!.notes).toBe('Line one\nLine two keeps its break.');
    expect(r.plan.checklist).toEqual(v1.checklist);
  });
  it('maps metadata and preferences', () => {
    if (!r.ok) throw new Error('import failed');
    expect(r.plan.info.planName).toBe('Morgan Household (sample)');
    expect(r.plan.info.region).toBe('Exampleville');
    expect(r.plan.info.trustedContact).toBe('Pat Lee, 555-0140');
    expect(r.plan.preferences.privacyDefault).toBe(true);
    expect(r.plan.preferences.includePrivateInPrint).toBe(false);
    expect(r.plan.schemaVersion).toBe(SCHEMA_VERSION);
  });
  it('reports migration actions in the preview', () => {
    if (!r.ok) throw new Error('import failed');
    expect(r.preview.sourceVersion).toBe(1);
    expect(r.preview.actions.join(' ')).toMatch(/version 1/);
    expect(r.preview.totalRecords).toBe(10);
    expect(r.preview.warnings).toEqual([]);
  });
  it('moves a non-empty v1 meeting point into Notes instead of dropping it', () => {
    const v1 = JSON.parse(legacyText);
    v1.meta.meetup = 'Library parking lot';
    const r2 = parseBackup(JSON.stringify(v1), { now: NOW });
    if (!r2.ok) throw new Error('import failed');
    expect(r2.plan.records.notes.some((n) => n.details === 'Library parking lot')).toBe(true);
  });
});

describe('round trip', () => {
  it('export then import yields an identical plan', () => {
    const plan = samplePlan(NOW);
    const text = serializeBackup(plan, '0.0.0', NOW);
    const r = parseBackup(text, { now: NOW });
    if (!r.ok) throw new Error(r.error);
    expect(r.plan).toEqual(plan);
    expect(r.preview.warnings).toEqual([]);
    expect(r.preview.actions).toEqual([]);
    expect(r.preview.exportedAt).toBe(NOW.toISOString());
    expect(r.preview.isSample).toBe(true);
  });
  it('round trips an empty plan', () => {
    const plan = blankPlan(NOW);
    const r = parseBackup(serializeBackup(plan, '0.0.0', NOW), { now: NOW });
    expect(r.ok && r.plan).toEqual(plan);
  });
  it('is rejected by the v1 app import check, so v1 cannot half-load it', () => {
    const out = JSON.parse(serializeBackup(samplePlan(NOW), '0.0.0', NOW));
    // v1 accepted a file when: data.meta && Array.isArray(data.checklist)
    expect(Boolean(out.meta && Array.isArray(out.checklist))).toBe(false);
  });
  it('names files with the date', () => {
    expect(backupFileName(new Date(2026, 0, 5))).toBe('family-continuity-backup-2026-01-05.json');
  });
});

describe('invalid and malicious files', () => {
  const bad = (text: string) => {
    const r = parseBackup(text, { now: NOW });
    expect(r.ok).toBe(false);
    return r.ok ? '' : r.error;
  };
  it('rejects empty, non-JSON, and wrong shapes with clear messages', () => {
    expect(bad('')).toMatch(/empty/);
    expect(bad('not json {')).toMatch(/could not be read/);
    expect(bad('[]')).toMatch(/does not contain a plan/);
    expect(bad('"hello"')).toMatch(/does not contain a plan/);
    expect(bad('{"foo":1}')).toMatch(/not a Family Continuity Planner backup/);
    expect(bad('{"schema":"other-app","schemaVersion":2}')).toMatch(/different application/);
  });
  it('rejects backups from a newer schema without guessing', () => {
    expect(bad(JSON.stringify({ schema: 'family-continuity-planner', schemaVersion: 99 }))).toMatch(/newer version/);
  });
  it('rejects oversized files before parsing', () => {
    expect(bad(' '.repeat(LIMITS.fileBytes + 1) + '{}')).toMatch(/larger than 10 MB/);
  });
  it('strips prototype pollution keys and never pollutes Object.prototype', () => {
    const text = '{"schema":"family-continuity-planner","schemaVersion":2,"__proto__":{"polluted":true},"meta":{"__proto__":{"polluted":true},"planName":"A"},"records":{"people":[{"id":"p1","name":"X","constructor":{"prototype":{"polluted":true}}}]}}';
    const r = parseBackup(text, { now: NOW });
    expect(r.ok).toBe(true);
    expect(({} as Record<string, unknown>).polluted).toBeUndefined();
    if (!r.ok) return;
    expect(Object.getPrototypeOf(r.plan.info)).toBe(Object.prototype);
    expect(r.preview.warnings[0]).toMatch(/unsafe field name/);
  });
  it('replaces unsafe IDs that could break out of HTML attributes', () => {
    const v1 = JSON.parse(legacyText);
    v1.people[0].id = 'x" autofocus onfocus="window.__xss=1';
    const r = parseBackup(JSON.stringify(v1), { now: NOW });
    if (!r.ok) throw new Error(r.error);
    expect(r.plan.records.people[0]!.id).toMatch(/^[A-Za-z0-9_-]+$/);
    expect(r.preview.warnings.join(' ')).toMatch(/unsafe record ID/);
  });
  it('replaces duplicate IDs so edits cannot hit the wrong record', () => {
    const v1 = JSON.parse(legacyText);
    v1.people[1].id = v1.people[0].id;
    const r = parseBackup(JSON.stringify(v1), { now: NOW });
    if (!r.ok) throw new Error(r.error);
    expect(r.plan.records.people[0]!.id).not.toBe(r.plan.records.people[1]!.id);
  });
  it('clears invalid dates instead of crashing (v1 crashed on these)', () => {
    const v1 = JSON.parse(legacyText);
    v1.documents[0].expires = 'not-a-date';
    v1.plans[0].reviewed = '2026-02-30';
    const r = parseBackup(JSON.stringify(v1), { now: NOW });
    if (!r.ok) throw new Error(r.error);
    expect(r.plan.records.documents[0]!.expires).toBe('');
    expect(r.plan.records.plans[0]!.reviewed).toBe('');
    expect(r.preview.warnings.join(' ')).toMatch(/invalid date.*\(2 times\)|invalid date/);
  });
  it('drops non-text values, unknown fields, and non-object entries', () => {
    const v1 = JSON.parse(legacyText);
    v1.people.push({ id: 'ok1', name: { nested: true }, evil: '<script>' });
    v1.people.push('just a string', null, 42);
    const r = parseBackup(JSON.stringify(v1), { now: NOW });
    if (!r.ok) throw new Error(r.error);
    const added = r.plan.records.people.find((p) => p.id === 'ok1')!;
    expect(added.name).toBe('');
    expect('evil' in added).toBe(false);
    expect(r.plan.records.people).toHaveLength(3);
  });
  it('keeps checklist items with unknown groups so they are not lost', () => {
    const v1 = JSON.parse(legacyText);
    v1.checklist.push({ id: 'g1', group: 'Custom group', title: 'Hidden task', done: false });
    const r = parseBackup(JSON.stringify(v1), { now: NOW });
    expect(r.ok && r.plan.checklist.find((c) => c.id === 'g1')?.group).toBe('Custom group');
  });
  it('truncates absurdly long text and strips control characters', () => {
    const v1 = JSON.parse(legacyText);
    v1.notes[0].details = 'a'.repeat(LIMITS.fieldChars + 50);
    v1.notes[0].name = 'Bell\u0007 and tab\tkept';
    const r = parseBackup(JSON.stringify(v1), { now: NOW });
    if (!r.ok) throw new Error(r.error);
    expect(r.plan.records.notes[0]!.details).toHaveLength(LIMITS.fieldChars);
    expect(r.plan.records.notes[0]!.name).toBe('Bell and tab\tkept');
  });
  it('treats markup as plain text (rendering is responsible for display, data is kept verbatim)', () => {
    const v1 = JSON.parse(legacyText);
    v1.people[0].name = '<img src=x onerror=alert(1)>';
    const r = parseBackup(JSON.stringify(v1), { now: NOW });
    expect(r.ok && r.plan.records.people[0]!.name).toBe('<img src=x onerror=alert(1)>');
  });
});

describe('safeJsonParse', () => {
  it('removes forbidden keys at any depth', () => {
    const r = safeJsonParse('{"a":{"__proto__":{"x":1},"b":[{"constructor":1}]}}');
    expect(r.ok && r.removedKeys).toBe(2);
  });
});
